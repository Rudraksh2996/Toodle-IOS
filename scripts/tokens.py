#!/usr/bin/env python3
"""Colour tokens for Toodle. OKLCH here is the source of truth.

  python3 scripts/tokens.py                 # check contrast, write Toodle/Theme/Palette.swift
  python3 scripts/tokens.py --preview DIR   # also render foil previews (needs numpy + Pillow)

Every foil colour is PROVISIONAL: picked by hand, not sampled from photos of real foil.
"""
import math
import pathlib
import sys

# (L, C, h). No hue in 170-215: teal is reserved for the logo (rule 4).
# Foil ramp goes highlight -> shadow, with the hue shifting along it.
# Chroma stays <= 0.07: spectral colour is an accent, never a fill.
THEMES = {
    "light": {
        "foil": [(0.975, 0.008, 250), (0.930, 0.035, 235), (0.880, 0.060, 320), (0.840, 0.055, 85), (0.740, 0.030, 265)],
        "paper": (0.985, 0.004, 95),
        "ink": (0.220, 0.015, 260),
        "inkMuted": (0.420, 0.015, 260),
        "dot": (0.550, 0.020, 260),
    },
    "dark": {
        "foil": [(0.300, 0.012, 250), (0.360, 0.035, 235), (0.400, 0.060, 320), (0.440, 0.055, 85), (0.200, 0.020, 265)],
        "paper": (0.180, 0.006, 260),
        "ink": (0.955, 0.006, 95),
        "inkMuted": (0.780, 0.010, 95),
        "dot": (0.700, 0.020, 260),
    },
}
PAPER_ALPHA = {"light": 0.94, "dark": 0.92}  # mirrored in Theme.Paper.opacity
NOISE = 0.035                                 # mirrored in Theme.Noise.opacity
MIN_BODY_CONTRAST = 4.5


def oklch_to_srgb(L, C, h):
    a, b = C * math.cos(math.radians(h)), C * math.sin(math.radians(h))
    l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s = (L - 0.0894841775 * a - 1.2914855480 * b) ** 3
    lin = (4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
           -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
           -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s)
    assert all(-1e-4 <= c <= 1 + 1e-4 for c in lin), f"oklch({L} {C} {h}) is outside sRGB"
    enc = lambda c: 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055
    return tuple(min(1.0, max(0.0, enc(c))) for c in lin)


def luminance(rgb):  # WCAG 2.2 relative luminance
    lin = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in rgb]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def contrast(a, b):
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def mix(a, b, t):  # source-over in gamma-encoded sRGB, as Core Graphics composites by default
    return tuple(x * (1 - t) + y * t for x, y in zip(a, b))


def check(name, t):
    """Worst case under text: paper panel over any foil stop or dot, with noise pushed either way."""
    paper = oklch_to_srgb(*t["paper"])
    under = [oklch_to_srgb(*c) for c in t["foil"] + [t["dot"]]]
    under += [mix(u, (1, 1, 1), NOISE) for u in under] + [mix(u, (0, 0, 0), NOISE) for u in under]
    worst = {}
    for role in ("ink", "inkMuted"):
        ink = oklch_to_srgb(*t[role])
        worst[role] = min(contrast(ink, mix(u, paper, PAPER_ALPHA[name])) for u in under)
        assert worst[role] >= MIN_BODY_CONTRAST, f"{name}.{role} worst-case contrast {worst[role]:.2f} < 4.5"
    return worst


def hexstr(rgb):
    return "0x" + "".join(f"{round(c * 255):02X}" for c in rgb)


def swift(themes):
    lines = [
        "// Generated by scripts/tokens.py. Edit the OKLCH values there, not here.",
        "// PROVISIONAL: foil colours are hand-picked, not sampled from photos of real foil.",
        "import SwiftUI",
        "",
        "enum Palette {",
    ]
    L, D = themes["light"], themes["dark"]
    for role in ("paper", "ink", "inkMuted", "dot"):
        lines.append(f"    /// light oklch{L[role]}, dark oklch{D[role]}")
        lines.append(f"    static let {role} = Color(light: {hexstr(oklch_to_srgb(*L[role]))}, dark: {hexstr(oklch_to_srgb(*D[role]))})")
    lines.append("    /// Foil ramp, highlight to shadow. Index 0 is also the base the foil sits on.")
    lines.append("    static let foil: [Color] = [")
    for lc, dc in zip(L["foil"], D["foil"]):
        lines.append(f"        Color(light: {hexstr(oklch_to_srgb(*lc))}, dark: {hexstr(oklch_to_srgb(*dc))}), // oklch{lc} / oklch{dc}")
    lines += [
        "    ]",
        "    static var foilBase: Color { foil[0] }",
        "}",
        "",
        "private extension Color {",
        "    init(light: UInt32, dark: UInt32) {",
        "        self.init(uiColor: UIColor { $0.userInterfaceStyle == .dark ? UIColor(rgb: dark) : UIColor(rgb: light) })",
        "    }",
        "}",
        "",
        "private extension UIColor {",
        "    convenience init(rgb: UInt32) {",
        "        self.init(red: CGFloat(rgb >> 16 & 0xFF) / 255, green: CGFloat(rgb >> 8 & 0xFF) / 255, blue: CGFloat(rgb & 0xFF) / 255, alpha: 1)",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def preview(out_dir):
    """Procedural bent foil: 3 soft fold bands, light-to-shadow across each band, hue shifting along the ramp."""
    import numpy as np
    from PIL import Image

    w, h = 1170, 2532  # iPhone 15 portrait, px
    y, x = np.mgrid[0:h, 0:w].astype(np.float32)
    x, y = x / w, y / w
    bands = [(0.15, 0.55, 22, 0.32), (0.80, 1.20, -14, 0.26), (0.40, 1.85, 31, 0.36)]  # (cx, cy, angle deg, width)
    for name, t in THEMES.items():
        ramp = np.array([oklch_to_srgb(*c) for c in t["foil"]], dtype=np.float32)
        img = np.broadcast_to(ramp[0], (h, w, 3)).copy()
        for cx, cy, ang, bw in bands:
            a = math.radians(ang)
            d = ((x - cx) * math.cos(a) + (y - cy) * math.sin(a)) / bw  # signed distance across the band
            weight = np.exp(-d * d * 2.0)[..., None]                   # soft fold, no hard edges
            pos = np.clip((d + 1.2) / 2.4, 0, 1) * (len(ramp) - 1)      # light side -> shadow side
            i = np.minimum(pos.astype(int), len(ramp) - 2)
            f = (pos - i)[..., None]
            img = img * (1 - weight) + (ramp[i] * (1 - f) + ramp[i + 1] * f) * weight
        img += (np.random.default_rng(7).random((h, w, 1), dtype=np.float32) - 0.5) * NOISE
        path = pathlib.Path(out_dir) / f"foil-{name}.png"
        Image.fromarray((np.clip(img, 0, 1) * 255).astype(np.uint8)).save(path)
        print("wrote", path)


if __name__ == "__main__":
    for name, t in THEMES.items():
        worst = check(name, t)
        print(f"{name}: worst-case body contrast ink {worst['ink']:.2f}:1, inkMuted {worst['inkMuted']:.2f}:1")
    out = pathlib.Path(__file__).resolve().parent.parent / "Toodle/Theme/Palette.swift"
    out.parent.mkdir(exist_ok=True)
    out.write_text(swift(THEMES))
    print("wrote", out)
    if "--preview" in sys.argv:
        preview(sys.argv[sys.argv.index("--preview") + 1])
